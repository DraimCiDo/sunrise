#!/usr/bin/env python3
"""Give every exported handler trait of the mod API vocabulary its hidden marks method.

Run once from the repository root: after the trait's opening brace it inserts

    #[doc(hidden)]
    fn __sunrise_marks(&self, _: crate::__private::Sealed) {
        __sunrise_handler_marks!(Trait);
    }

(`__sunrise_handler_marks!` is generated by sunrise-mod-api-gen from the call table), so a mod
that holds a handler of the trait imports every method of it.
"""
import re
import subprocess

TRAITS = """BiomeColorResolver BlockCapabilityProvider BlockEntityTransform BlockTintSource
ClientItemExtensions ClientReloadListener CommandArgumentType CraftingRecipeHandler CrashSection
CriterionTest EnchantmentDamageEffect EnergyHandler EntityCapabilityProvider EntityRenderLayer
EntityRenderer EntitySelectorType GameTestFunction GlobalLootModifier GlobalLootModifierSerializer
GroundStateProvider IPayloadHandler Interaction ItemCapabilityProvider ItemContainerProvider
ItemStorage LoadCondition ModLootCondition ModLootFunction ParticleProvider PayloadWork
PlaceProvider ReloadApply ResourceHandler RuntimeFileSource SectionGeometry ServerReloadListener
SpecialModelRenderer StartupScreen StructurePiece StructureType SuggestionProvider
TooltipAppender""".split()
ROOT = "crates/sunrise-mod-vocab/src/"

done = set()
for path in subprocess.check_output(["rg", "-l", r"^\s*pub trait ", ROOT], text=True).split():
    source = open(path).read()
    changed = False
    for name in TRAITS:
        if name in done:
            continue
        found = re.search(r"^([ \t]*)pub trait " + name + r"\b", source, re.M)
        if not found:
            continue
        i, depth = found.end(), 0
        while True:  # the body's brace: the first one outside the generics
            c = source[i]
            if c == "<":
                depth += 1
            elif c == ">" and source[i - 1] != "-":
                depth -= 1
            elif c == "{" and depth == 0:
                break
            i += 1
        pad = found.group(1) + "    "
        method = (
            f"\n{pad}#[doc(hidden)]\n{pad}fn __sunrise_marks(&self, _: crate::__private::Sealed) {{\n"
            f"{pad}    __sunrise_handler_marks!({name});\n{pad}}}"
        )
        source = source[: i + 1] + method + source[i + 1 :]
        changed = True
        done.add(name)
    if changed:
        open(path, "w").write(source)
missing = sorted(set(TRAITS) - done)
if missing:
    raise SystemExit(f"no declaration found for {missing}")
